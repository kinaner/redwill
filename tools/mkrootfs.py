#!/usr/bin/env python3
"""Packs rootfs/ into a C header: every file becomes part of the RAM disk C:\\ at boot.
Every .rpp is also compiled with rppc into a .rxe placed next to it.
Usage: mkrootfs.py rootfs_dir rppc_binary out.h"""
import os, subprocess, sys, tempfile
root, rppc, out = sys.argv[1:4]
files = []
tmp = tempfile.mkdtemp()
for dp, dn, fn in os.walk(root):
    dn.sort()
    for f in sorted(fn):
        full = os.path.join(dp, f); rel = os.path.relpath(full, root).replace('/', '\\')
        files.append(("C:\\" + rel, open(full, 'rb').read()))
        if f.lower().endswith('.rpp'):
            o = os.path.join(tmp, f[:-4] + '.rxe')
            r = subprocess.run([rppc, full, '-o', o], capture_output=True, text=True)
            if r.returncode: sys.exit("rppc failed on %s:\n%s%s" % (full, r.stdout, r.stderr))
            files.append(("C:\\" + rel[:-4] + '.rxe', open(o, 'rb').read()))
blob = bytearray(); table = []
for p, d in files:
    table.append((p, len(blob), len(d))); blob += d
with open(out, 'w') as h:
    h.write("/* generated by tools/mkrootfs.py - do not edit */\n#define ROOTFS_COUNT %d\n" % len(table))
    h.write("static const struct { const char *path; int off, len; } ROOTFS[ROOTFS_COUNT] = {\n")
    for p, o, l in table: h.write('  { "%s", %d, %d },\n' % (p.replace('\\', '\\\\'), o, l))
    h.write("};\nstatic const u8 ROOTFS_DATA[%d] = {\n" % (len(blob) + 1))
    for i in range(0, len(blob), 24): h.write(",".join(str(b) for b in blob[i:i + 24]) + ",\n")
    h.write("0};\n")
print("rootfs: %d files, %d bytes" % (len(table), len(blob)))
