#!/usr/bin/env python3
"""Converts inter32/icons/*.ico into a C header of 32x32 ARGB arrays for the kernel.
Usage: ico2c.py icons_dir out.h   (order of ICON_NAMES = icon index used by kernel/ui/icons.h)"""
import sys, os
from PIL import Image
ICON_NAMES = ["notepad", "calculator", "folder", "terminal", "paint", "about", "snake", "settings", "browser", "document"]
def main():
    src, out = sys.argv[1], sys.argv[2]
    lines = ["/* generated by tools/ico2c.py from inter32/icons - do not edit */",
             "#define ICO_COUNT %d" % len(ICON_NAMES), "static const u32 ICO_DATA[ICO_COUNT][1024] = {"]
    for n in ICON_NAMES:
        im = Image.open(os.path.join(src, n + ".ico")).convert("RGBA")
        if im.size != (32, 32): im = im.resize((32, 32), Image.NEAREST)
        px = ["0x%08X" % ((a << 24) | (r << 16) | (g << 8) | b) for (r, g, b, a) in im.getdata()]
        lines.append("  /* %s */ {" % n)
        for i in range(0, 1024, 16): lines.append("    " + ",".join(px[i:i + 16]) + ",")
        lines.append("  },")
    lines.append("};")
    open(out, "w").write("\n".join(lines) + "\n")
main()
