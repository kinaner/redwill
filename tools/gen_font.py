#!/usr/bin/env python3
"""Rasterises anti-aliased glyph atlases (ASCII 32..126) from DejaVu Sans Mono into kernel/gfx/font_data.h.
  FONT_S : 8x16  8-bit alpha, regular   (all normal UI text, fixed 8px advance)
  FONT_L : 24x48 8-bit alpha, bold      (big() titles, scaled at draw time)
Usage: gen_font.py [out.h]   (needs Pillow + DejaVu fonts; the generated header is committed, the build does not need them)"""
import sys, os
from PIL import Image, ImageDraw, ImageFont
D = "/usr/share/fonts/truetype/dejavu/"
def atlas(path, size, w, h, base):
    f = ImageFont.truetype(path, size); out = []
    for ch in range(32, 127):
        im = Image.new("L", (w, h), 0)
        adv = f.getlength(chr(ch)); dx = (w - adv) / 2
        ImageDraw.Draw(im).text((dx, base), chr(ch), font=f, fill=255, anchor="ls")
        out.append(list(im.getdata()))
    return out
def emit(name, data, n):
    s = ["static const u8 %s[95][%d] = {" % (name, n)]
    for g in data: s.append("  {" + ",".join(str(v) for v in g) + "},")
    s.append("};"); return "\n".join(s)
def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "kernel", "gfx", "font_data.h")
    small = atlas(D + "DejaVuSansMono.ttf", 13.3, 8, 16, 12)
    big = atlas(D + "DejaVuSansMono-Bold.ttf", 40, 24, 48, 37)
    open(out, "w").write("/* generated by tools/gen_font.py - DejaVu Sans Mono (Bitstream Vera licence, see LICENSE-FONT.txt) */\n"
                         + emit("FONT_S", small, 128) + "\n" + emit("FONT_L", big, 1152) + "\n")
main()
